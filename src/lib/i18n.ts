/** Convenience hook: `const { t, lang, toggle } = useT()` */
export function useT() {
  const lang = useLang((s) => s.lang);
  const toggle = useLang((s) => s.toggle);
  return { t: tFor(lang), lang, toggle, isUr: lang === "ur" };
}
